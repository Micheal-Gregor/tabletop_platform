"""Write one facet's slice (TE-4): the table rows and hook lines of the named ids, with each table's header.

Usage: python slice.py <spec.json> <out.md>
spec: {"title": str, "sources": [{"path": str, "ids": [str, ...], "sections": [heading, ...]}]}
A row is kept when its first cell is one of the ids; a hook line when it starts "HOOK <id> ".
A section is kept whole when its heading line (without the leading #s) is listed.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SEPARATOR = re.compile(r"^\|\s*:?-{3,}")


def cells(line: str) -> list[str]:
    """A table row's cells, stripped; an escaped pipe stays inside its cell."""
    parts = re.split(r"(?<!\\)\|", line.strip().strip("|"))
    return [p.strip() for p in parts]


def tables(lines: list[str]):
    """Each table as (header cells, [row cells]), in order."""
    for i in range(len(lines)):
        if opens_table(lines, i):
            rows = [cells(r) for r in lines[i + 2:i + 2 + rows_after(lines, i + 2)]]
            yield cells(lines[i]), rows


def rows_after(lines: list[str], start: int) -> int:
    n = 0
    while start + n < len(lines) and lines[start + n].startswith("|"):
        n += 1
    return n


def first_cell(line: str) -> str:
    return line.split("|")[1].strip().strip("*") if line.startswith("|") else ""


def matches(line: str, ids: set) -> bool:
    """A table row whose first cell is a listed id, or a hook line naming one."""
    hook = line.startswith("HOOK ") and line.split()[1] in ids
    return hook or first_cell(line) in ids


def opens_table(lines: list[str], i: int) -> bool:
    return i + 1 < len(lines) and lines[i].startswith("|") and bool(SEPARATOR.match(lines[i + 1]))


def kept_rows(lines: list[str], ids: set) -> list[str]:
    """Matching rows and hook lines, each table's header emitted once before its first match."""
    out, header = [], []
    for i, line in enumerate(lines):
        if opens_table(lines, i):
            header = [""] + lines[i:i + 2]
        elif matches(line, ids):
            out.extend(header)
            header = []
            out.append(line)
        elif not line.startswith("|"):
            header = []
    return out


def kept_sections(lines: list[str], headings: set) -> list[str]:
    """Whole sections whose heading text is listed, up to the next heading of the same or higher level."""
    out, level = [], 0
    for line in lines:
        depth = len(line) - len(line.lstrip("#")) if line.startswith("#") else 0
        if depth and level and depth <= level:
            level = 0
        if depth and line.lstrip("#").strip() in headings:
            level = depth
        if level:
            out.append(line)
    return out


def main() -> int:
    spec = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    out = [f"# {spec['title']}", "", "Generated by `slice.py` from the files named below; rows are verbatim."]
    for src in spec["sources"]:
        lines = (ROOT / src["path"]).read_text(encoding="utf-8").splitlines()
        out += ["", f"## From `{src['path']}`"]
        out += kept_sections(lines, set(src.get("sections", [])))
        out += kept_rows(lines, set(src.get("ids", [])))
    Path(sys.argv[2]).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
